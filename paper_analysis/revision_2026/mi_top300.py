"""Composition of the MI top-300 feature set (same recipe as modelling/src/03_loso.ipynb: MI vs raw AOD, random_state=42)."""
import sys, json, numpy as np, pandas as pd
from sklearn.feature_selection import mutual_info_regression
import os
from pathlib import Path
REPO = Path(__file__).resolve().parents[2]   # repository root
DATASET = Path(os.environ.get('AOD_DATASET', REPO / 'data' / 'dataset.csv'))   # download dataset.csv from the Hugging Face dataset
sys.path.insert(0,str(Path(__file__).resolve().parent))
from feature_families import cat
jobs={'stratified':str(FEAT/'stratified/train.csv'),'holdout_time':str(FEAT/'holdout_time/train.csv'),'loso_Shagaya_Park':str(FEAT/'loso/Shagaya_Park/train.csv')}
FEAT = Path(os.environ.get('AOD_FEATURES', REPO/'feature_engineering/features'))   # feature CSVs are regenerated by feature_engineering/src/02_features.ipynb and 02b_features_loso.ipynb
out={}
for name,p in jobs.items():
    df=pd.read_csv(p); cols=[c for c in df.columns if c!='AOD_550nm']
    X=df[cols].values.astype(np.float32); y=df['AOD_550nm'].values
    from joblib import Parallel, delayed
    chunks=np.array_split(np.arange(X.shape[1]),40)
    mi=np.concatenate(Parallel(n_jobs=4)(delayed(mutual_info_regression)(X[:,c],y,random_state=42) for c in chunks))
    top=np.argsort(mi)[::-1][:300]; names=[cols[i] for i in top]
    cats=pd.Series([cat(c) for c in names]).value_counts().to_dict()
    meta=[c for c in names if cat(c)=='meta']
    rank_meta={c:int(np.where(np.array(cols)[np.argsort(mi)[::-1]]==c)[0][0])+1 for c in cols if cat(c)=='meta'}
    out[name]={'n_features':len(cols),'top300_by_category':cats,'meta_in_top300':meta,'meta_rank':rank_meta}
    print(name,out[name],flush=True)
json.dump(out,open(REPO/'paper_analysis/outputs/mi_top300.json','w'),indent=1)
